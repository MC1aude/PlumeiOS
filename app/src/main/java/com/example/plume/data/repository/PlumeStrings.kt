object PlumeStrings {

    fun get(key: String, language: AppLanguage): String {
        return when (language) {
            AppLanguage.RUSSIAN -> ruStrings[key] ?: enStrings[key] ?: key
            AppLanguage.ENGLISH -> enStrings[key] ?: key
            AppLanguage.UKRAINIAN -> ukStrings[key] ?: enStrings[key] ?: key
            AppLanguage.POLISH -> plStrings[key] ?: enStrings[key] ?: key
        }
    }

    /**
     * Proper pluralization formatting for track counts across supported languages.
     * Polish: 1 utwór, 2-4 utwory, 0 / 5+ utworów
     * Russian: 1 трек, 2-4 трека, 0 / 5+ треков
     * Ukrainian: 1 трек, 2-4 треки, 0 / 5+ треків
     * English: 1 track, 0 / 2+ tracks
     */
    fun formatTrackCount(count: Int, language: AppLanguage): String {
        val noun = when (language) {
            AppLanguage.POLISH -> when {
                count == 1 -> "utwór"
                count % 10 in 2..4 && count % 100 !in 12..14 -> "utwory"
                else -> "utworów"
            }
            AppLanguage.RUSSIAN -> when {
                count % 10 == 1 && count % 100 != 11 -> "трек"
                count % 10 in 2..4 && count % 100 !in 12..14 -> "трека"
                else -> "треков"
            }
            AppLanguage.UKRAINIAN -> when {
                count % 10 == 1 && count % 100 != 11 -> "трек"
                count % 10 in 2..4 && count % 100 !in 12..14 -> "треки"
                else -> "треків"
            }
            AppLanguage.ENGLISH -> when {
                count == 1 -> "track"
                else -> "tracks"
            }
        }
        return "$count $noun"
    }

